/** Мини-разметка: заголовки, списки, жирный. Полноценный markdown здесь избыточен. */
function toHtml(markdown) {
  const lines = markdown.split('\n')
  const out = []
  let list = false
  let paragraph = []

  const flushParagraph = () => {
    if (!paragraph.length) return
    out.push('<p>' + inline(paragraph.join(' ')) + '</p>')
    paragraph = []
  }

  const closeList = () => {
    if (list) {
      out.push('</ul>')
      list = false
    }
  }

  const inline = (t) => esc(t).replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')

  for (const raw of lines) {
    const line = raw.trimEnd()

    if (!line.trim()) {
      flushParagraph()
      closeList()
      continue
    }

    if (line.startsWith('# ')) {
      flushParagraph()
      closeList()
      out.push('<h1>' + inline(line.slice(2)) + '</h1>')
      continue
    }

    if (line.startsWith('## ')) {
      flushParagraph()
      closeList()
      out.push('<h2>' + inline(line.slice(3)) + '</h2>')
      continue
    }

    if (line.startsWith('- ')) {
      flushParagraph()
      if (!list) {
        out.push('<ul>')
        list = true
      }
      out.push('<li>' + inline(line.slice(2)) + '</li>')
      continue
    }

    closeList()
    paragraph.push(line.trim())
  }

  flushParagraph()
  closeList()
  return out.join('\n')
}

