const esc = (s) =>
  String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')

const today = () =>
  new Date().toLocaleDateString('ru-RU', { day: 'numeric', month: 'long', year: 'numeric' })

function operatorLine(s) {
  const parts = [s.legal, s.inn ? 'ИНН ' + s.inn : '']. filter(Boolean)
  return parts.join(', ')
}

